part of 'compliance_resource.dart';

/// Enterprise Compliance content, application sessions, and Code Artifacts.
///
/// Use a Compliance Access Key with `read:compliance_user_data` for reads and
/// downloads or `delete:compliance_user_data` for destructive calls.
final class ComplianceAppsResource {
  final ComplianceResource _resource;

  ComplianceAppsResource._(this._resource);

  /// Lists chats, using opaque ID cursors for subsequent pages.
  ///
  /// Organization-wide queries use forward pagination only. When filtering an
  /// organization-wide query by time, use the matching [orderBy] field.
  /// [projectIds] requires [userIds]. Updated-time polling omits [userIds].
  Future<ComplianceIdPage<ComplianceChat>> listChats({
    String? beforeId,
    String? afterId,
    int? limit,
    ComplianceChatOrderBy? orderBy,
    List<String>? organizationIds,
    List<String>? projectIds,
    List<String>? userIds,
    ComplianceTimeRange? createdAt,
    ComplianceTimeRange? updatedAt,
    Future<void>? abortTrigger,
  }) => _resource._get(
    'apps/chats',
    (json) => ComplianceIdPage.fromJson(
      json,
      ComplianceChat.fromJson,
      requirePagination: true,
    ),
    query: {
      'before_id': ?beforeId,
      'after_id': ?afterId,
      'limit': ?limit?.toString(),
      'order_by': ?orderBy?.wireValue,
      'organization_ids[]': ?organizationIds,
      'project_ids[]': ?projectIds,
      'user_ids[]': ?userIds,
      ...?createdAt?.toQueryParameters('created_at'),
      ...?updatedAt?.toQueryParameters('updated_at'),
    },
    abortTrigger: abortTrigger,
  );

  /// Permanently deletes a chat and returns the receipt if supplied.
  Future<ComplianceDeletion?> deleteChat(
    String chatId, {
    Future<void>? abortTrigger,
  }) => _delete(
    'apps/chats/${_segment(chatId)}',
    'claude_chat_deleted',
    abortTrigger,
  );

  /// Retrieves a chat's metadata and a page of its messages.
  Future<ComplianceChatMessages> listChatMessages(
    String chatId, {
    String? beforeId,
    String? afterId,
    int? limit,
    ComplianceOrder? order,
    ComplianceTimeRange? createdAt,
    ComplianceTimeRange? updatedAt,
    int? toolResultMaxChars,
    int? toolUseInputMaxChars,
    Future<void>? abortTrigger,
  }) => _retrieve(
    'apps/chats/${_segment(chatId)}/messages',
    ComplianceChatMessages.fromJson,
    query: {
      'before_id': ?beforeId,
      'after_id': ?afterId,
      'limit': ?limit?.toString(),
      'order': ?order?.name,
      ...?createdAt?.toQueryParameters('created_at'),
      ...?updatedAt?.toQueryParameters('updated_at'),
      'tool_result_max_chars': ?toolResultMaxChars?.toString(),
      'tool_use_input_max_chars': ?toolUseInputMaxChars?.toString(),
    },
    abortTrigger: abortTrigger,
  );

  /// Retrieves metadata for an uploaded chat file.
  Future<ComplianceFileMetadata> retrieveChatFile(
    String fileId, {
    Future<void>? abortTrigger,
  }) => _retrieve(
    'apps/chats/files/${_segment(fileId)}',
    ComplianceFileMetadata.fromJson,
    abortTrigger: abortTrigger,
  );

  /// Permanently deletes an uploaded chat file and returns the receipt if supplied.
  Future<ComplianceDeletion?> deleteChatFile(
    String fileId, {
    Future<void>? abortTrigger,
  }) => _delete(
    'apps/chats/files/${_segment(fileId)}',
    'claude_file_deleted',
    abortTrigger,
  );

  /// Streams an uploaded chat file as bytes.
  Stream<List<int>> downloadChatFile(
    String fileId, {
    void Function(ComplianceDownloadHeaders)? onResponse,
    Future<void>? abortTrigger,
  }) => _download(
    'apps/chats/files/${_segment(fileId)}/content',
    onResponse: onResponse,
    abortTrigger: abortTrigger,
  );

  /// Retrieves metadata for a file generated by Claude.
  Future<ComplianceFileMetadata> retrieveGeneratedChatFile(
    String generatedFileId, {
    Future<void>? abortTrigger,
  }) => _retrieve(
    'apps/chats/generated-files/${_segment(generatedFileId)}',
    ComplianceFileMetadata.fromJson,
    abortTrigger: abortTrigger,
  );

  /// Streams a Claude-generated file as bytes.
  Stream<List<int>> downloadGeneratedChatFile(
    String generatedFileId, {
    void Function(ComplianceDownloadHeaders)? onResponse,
    Future<void>? abortTrigger,
  }) => _download(
    'apps/chats/generated-files/${_segment(generatedFileId)}/content',
    onResponse: onResponse,
    abortTrigger: abortTrigger,
  );

  /// Lists projects visible to the caller's Compliance key.
  Future<ComplianceCursorPage<ComplianceProject>> listProjects({
    String? page,
    int? limit,
    List<String>? organizationIds,
    List<String>? userIds,
    ComplianceTimeRange? createdAt,
    ComplianceTimeRange? updatedAt,
    Future<void>? abortTrigger,
  }) => _resource._getPage(
    'apps/projects',
    ComplianceProject.fromJson,
    page: page,
    limit: limit,
    query: {
      'organization_ids[]': ?organizationIds,
      'user_ids[]': ?userIds,
      ...?createdAt?.toQueryParameters('created_at'),
      ...?updatedAt?.toQueryParameters('updated_at'),
    },
    abortTrigger: abortTrigger,
  );

  /// Retrieves details for a project.
  Future<ComplianceProject> retrieveProject(
    String projectId, {
    Future<void>? abortTrigger,
  }) => _retrieve(
    'apps/projects/${_segment(projectId)}',
    ComplianceProject.fromJson,
    abortTrigger: abortTrigger,
  );

  /// Permanently deletes a project and returns the receipt if supplied.
  Future<ComplianceDeletion?> deleteProject(
    String projectId, {
    Future<void>? abortTrigger,
  }) => _delete(
    'apps/projects/${_segment(projectId)}',
    'claude_project_deleted',
    abortTrigger,
  );

  /// Lists files and documents attached to a project.
  Future<ComplianceCursorPage<ComplianceProjectAttachment>>
  listProjectAttachments(
    String projectId, {
    String? page,
    int? limit,
    Future<void>? abortTrigger,
  }) => _resource._getPage(
    'apps/projects/${_segment(projectId)}/attachments',
    ComplianceProjectAttachment.fromJson,
    page: page,
    limit: limit,
    abortTrigger: abortTrigger,
  );

  /// Lists people, groups and organizations that can access a project.
  Future<ComplianceCursorPage<ComplianceProjectCollaborator>>
  listProjectCollaborators(
    String projectId, {
    String? page,
    int? limit,
    Future<void>? abortTrigger,
  }) => _resource._getPage(
    'apps/projects/${_segment(projectId)}/collaborators',
    ComplianceProjectCollaborator.fromJson,
    page: page,
    limit: limit,
    abortTrigger: abortTrigger,
  );

  /// Retrieves a project document and its text.
  Future<ComplianceProjectDocument> retrieveProjectDocument(
    String documentId, {
    Future<void>? abortTrigger,
  }) => _retrieve(
    'apps/projects/documents/${_segment(documentId)}',
    ComplianceProjectDocument.fromJson,
    abortTrigger: abortTrigger,
  );

  /// Retrieves metadata for a project document.
  Future<ComplianceFileMetadata> retrieveProjectDocumentMetadata(
    String documentId, {
    Future<void>? abortTrigger,
  }) => _retrieve(
    'apps/projects/documents/${_segment(documentId)}/metadata',
    ComplianceFileMetadata.fromJson,
    abortTrigger: abortTrigger,
  );

  /// Permanently deletes a project document and returns its receipt if supplied.
  Future<ComplianceDeletion?> deleteProjectDocument(
    String documentId, {
    Future<void>? abortTrigger,
  }) => _delete(
    'apps/projects/documents/${_segment(documentId)}',
    'claude_project_document_deleted',
    abortTrigger,
    requiresType: true,
  );

  /// Retrieves metadata for a chat artifact version.
  Future<ComplianceArtifactVersion> retrieveArtifactVersion(
    String artifactVersionId, {
    Future<void>? abortTrigger,
  }) => _retrieve(
    'apps/artifacts/${_segment(artifactVersionId)}',
    ComplianceArtifactVersion.fromJson,
    abortTrigger: abortTrigger,
  );

  /// Retrieves the full text and descriptive fields for a chat artifact version.
  Future<ComplianceArtifactContent> retrieveArtifactVersionContent(
    String artifactVersionId, {
    Future<void>? abortTrigger,
  }) => _retrieve(
    'apps/artifacts/${_segment(artifactVersionId)}/content',
    ComplianceArtifactContent.fromJson,
    abortTrigger: abortTrigger,
  );

  /// Lists local Claude application sessions.
  Future<ComplianceCursorPage<ComplianceSession>> listLocalSessions({
    String? page,
    int? limit,
    ComplianceTimeRange? createdAt,
    DateTime? updatedAtOrAfter,
    Future<void>? abortTrigger,
  }) => _resource._getPage(
    'apps/sessions/local',
    ComplianceSession.fromJson,
    cursorOnly: true,
    page: page,
    limit: limit,
    query: {
      ...?createdAt?.toQueryParameters('created_at'),
      'updated_at.gte': ?updatedAtOrAfter?.toUtc().toIso8601String(),
    },
    abortTrigger: abortTrigger,
  );

  /// Retrieves metadata for one local session.
  Future<ComplianceSession> retrieveLocalSession(
    String localSessionId, {
    Future<void>? abortTrigger,
  }) => _retrieve(
    'apps/sessions/local/${_segment(localSessionId)}',
    ComplianceSession.fromJson,
    abortTrigger: abortTrigger,
  );

  /// Retrieves a page of a local session's transcript.
  ///
  /// Follow the opaque token within 24 hours of the first page. Restart at
  /// the first page if the token expires. The API may include a retention
  /// placeholder for unavailable turns. For a page too large to read, retry
  /// from the first page in ascending order.
  Future<ComplianceSessionMessages> listLocalSessionMessages(
    String localSessionId, {
    String? page,
    int? limit,
    ComplianceOrder? order,
    int? toolResultMaxBytes,
    int? toolUseInputMaxBytes,
    Future<void>? abortTrigger,
  }) => _listTranscript(
    'apps/sessions/local/${_segment(localSessionId)}/messages',
    page: page,
    limit: limit,
    order: order,
    toolResultMaxBytes: toolResultMaxBytes,
    toolUseInputMaxBytes: toolUseInputMaxBytes,
    abortTrigger: abortTrigger,
  );

  /// Lists remote sessions run by Claude applications.
  Future<ComplianceCursorPage<ComplianceSession>> listRemoteSessions({
    String? page,
    int? limit,
    List<String>? organizationIds,
    List<String>? userIds,
    ComplianceTimeRange? createdAt,
    Future<void>? abortTrigger,
  }) => _resource._getPage(
    'apps/sessions/remote',
    ComplianceSession.fromJson,
    cursorOnly: true,
    page: page,
    limit: limit,
    query: {
      'organization_ids[]': ?organizationIds,
      'user_ids[]': ?userIds,
      ...?createdAt?.toQueryParameters('created_at'),
    },
    abortTrigger: abortTrigger,
  );

  /// Retrieves a page of a remote session's transcript.
  Future<ComplianceSessionMessages> listRemoteSessionMessages(
    String remoteSessionId, {
    String? page,
    int? limit,
    ComplianceOrder? order,
    int? toolResultMaxBytes,
    int? toolUseInputMaxBytes,
    Future<void>? abortTrigger,
  }) => _listTranscript(
    'apps/sessions/remote/${_segment(remoteSessionId)}/messages',
    page: page,
    limit: limit,
    order: order,
    toolResultMaxBytes: toolResultMaxBytes,
    toolUseInputMaxBytes: toolUseInputMaxBytes,
    abortTrigger: abortTrigger,
  );

  /// Lists Code Artifacts.
  ///
  /// Continue while [ComplianceCursorPage.nextPage] is present. The API may
  /// return a short or empty page with a cursor.
  Future<ComplianceCursorPage<ComplianceCodeArtifact>> listCodeArtifacts({
    String? page,
    int? limit,
    List<String>? organizationIds,
    List<String>? userIds,
    ComplianceTimeRange? updatedAt,
    Future<void>? abortTrigger,
  }) => _resource._getPage(
    'apps/code/artifacts',
    ComplianceCodeArtifact.fromJson,
    page: page,
    limit: limit,
    query: {
      'organization_ids[]': ?organizationIds,
      'user_ids[]': ?userIds,
      ...?updatedAt?.toQueryParameters('updated_at'),
    },
    abortTrigger: abortTrigger,
  );

  /// Streams an artifact version. Enable [allowZip] for multi-file versions.
  Stream<List<int>> downloadCodeArtifactVersion(
    String artifactId,
    String versionId, {
    bool allowZip = false,
    void Function(ComplianceDownloadHeaders)? onResponse,
    Future<void>? abortTrigger,
  }) => _download(
    'apps/code/artifacts/${_segment(artifactId)}/versions/${_segment(versionId)}',
    query: {if (allowZip) 'multi_file_format': 'zip'},
    onResponse: onResponse,
    abortTrigger: abortTrigger,
  );

  /// Streams an artifact's current content. Enable [allowZip] for a Claude Doc
  /// or for the latest version of a multi-file artifact.
  Stream<List<int>> downloadCodeArtifact(
    String artifactId, {
    bool allowZip = false,
    void Function(ComplianceDownloadHeaders)? onResponse,
    Future<void>? abortTrigger,
  }) => _download(
    'apps/code/artifacts/${_segment(artifactId)}/content',
    query: {if (allowZip) 'multi_file_format': 'zip'},
    onResponse: onResponse,
    abortTrigger: abortTrigger,
  );

  /// Permanently deletes a Code Artifact and its versions.
  ///
  /// A receipt indicates that deletion was initiated.
  Future<ComplianceDeletion?> deleteCodeArtifact(
    String artifactId, {
    Future<void>? abortTrigger,
  }) => _delete(
    'apps/code/artifacts/${_segment(artifactId)}',
    'code_artifact_deleted',
    abortTrigger,
    requiresType: true,
  );

  Future<ComplianceSessionMessages> _listTranscript(
    String path, {
    String? page,
    int? limit,
    ComplianceOrder? order,
    int? toolResultMaxBytes,
    int? toolUseInputMaxBytes,
    Future<void>? abortTrigger,
  }) => _retrieve(
    path,
    ComplianceSessionMessages.fromJson,
    query: {
      'page': ?page,
      'limit': ?limit?.toString(),
      'order': ?order?.name,
      'tool_result_max_bytes': ?toolResultMaxBytes?.toString(),
      'tool_use_input_max_bytes': ?toolUseInputMaxBytes?.toString(),
    },
    abortTrigger: abortTrigger,
  );

  Future<T> _retrieve<T extends ComplianceRecord>(
    String path,
    T Function(Map<String, dynamic>) decode, {
    Map<String, dynamic>? query,
    Future<void>? abortTrigger,
  }) => _resource._get(path, decode, query: query, abortTrigger: abortTrigger);

  Future<ComplianceDeletion?> _delete(
    String path,
    String expectedType,
    Future<void>? abortTrigger, {
    bool requiresType = false,
  }) async {
    final response = await _resource._send(
      'DELETE',
      path,
      abortTrigger: abortTrigger,
    );
    if (response.bodyBytes.isEmpty) return null;
    final receipt = ComplianceResource._decodeObject(
      response,
      ComplianceDeletion.fromJson,
    );
    if ((requiresType || receipt.type != null) &&
        receipt.type != expectedType) {
      throw FormatException(
        'Expected Compliance deletion type "$expectedType"',
      );
    }
    return receipt;
  }

  Stream<List<int>> _download(
    String path, {
    Map<String, dynamic>? query,
    void Function(ComplianceDownloadHeaders)? onResponse,
    Future<void>? abortTrigger,
  }) => getResourceByteStream(
    _resource,
    '/v1/compliance/$path',
    queryParams: query,
    headers: () => _resource._headers('*/*'),
    onResponse: onResponse == null
        ? null
        : (headers) =>
              onResponse(ComplianceDownloadHeaders.fromHeaders(headers)),
    abortTrigger: abortTrigger,
  );

  static String _segment(String value) => ComplianceResource._segment(value);
}
