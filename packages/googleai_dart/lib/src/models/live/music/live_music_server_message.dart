import 'dart:convert';
import 'dart:typed_data';

import 'live_music_generation_config.dart';

/// A message from the Live Music WebSocket.
class LiveMusicServerMessage {
  /// Acknowledgment of the setup frame.
  final Map<String, dynamic>? setupComplete;

  /// Generated audio chunks, when this message carries audio.
  final LiveMusicServerContent? serverContent;

  /// Information about a prompt filtered by the service.
  final LiveMusicFilteredPrompt? filteredPrompt;

  /// A non-terminal server warning.
  final String? warning;

  /// Unrecognized top-level fields from the server.
  final Map<String, dynamic> additionalProperties;

  /// Creates a server message.
  const LiveMusicServerMessage({
    this.setupComplete,
    this.serverContent,
    this.filteredPrompt,
    this.warning,
    this.additionalProperties = const {},
  });

  /// Parses a server message.
  factory LiveMusicServerMessage.fromJson(Map<String, dynamic> json) {
    final content = json['serverContent'] as Map<String, dynamic>?;
    final filtered = json['filteredPrompt'] as Map<String, dynamic>?;
    const known = {
      'setupComplete',
      'serverContent',
      'filteredPrompt',
      'warning',
    };
    return LiveMusicServerMessage(
      setupComplete: json['setupComplete'] as Map<String, dynamic>?,
      serverContent: content == null
          ? null
          : LiveMusicServerContent.fromJson(content),
      filteredPrompt: filtered == null
          ? null
          : LiveMusicFilteredPrompt.fromJson(filtered),
      warning: json['warning'] as String?,
      additionalProperties: {
        for (final entry in json.entries)
          if (!known.contains(entry.key)) entry.key: entry.value,
      },
    );
  }

  /// Converts to JSON.
  Map<String, dynamic> toJson() => {
    ...additionalProperties,
    'setupComplete': ?setupComplete,
    'serverContent': ?serverContent?.toJson(),
    'filteredPrompt': ?filteredPrompt?.toJson(),
    'warning': ?warning,
  };
}

/// Audio generated in a server update.
class LiveMusicServerContent {
  /// Audio chunks in delivery order.
  final List<LiveMusicAudioChunk>? audioChunks;

  /// Creates an audio update.
  const LiveMusicServerContent({this.audioChunks});

  /// Parses an audio update.
  factory LiveMusicServerContent.fromJson(Map<String, dynamic> json) =>
      LiveMusicServerContent(
        audioChunks: (json['audioChunks'] as List<dynamic>?)
            ?.map(
              (chunk) =>
                  LiveMusicAudioChunk.fromJson(chunk as Map<String, dynamic>),
            )
            .toList(),
      );

  /// Converts to JSON.
  Map<String, dynamic> toJson() => {
    'audioChunks': ?audioChunks?.map((chunk) => chunk.toJson()).toList(),
  };
}

/// A chunk of audio generated by Lyria RealTime.
class LiveMusicAudioChunk {
  /// Decoded audio bytes.
  final Uint8List? data;

  /// Media type reported by the service.
  final String? mimeType;

  /// The prompts and settings applied when generating this chunk.
  final LiveMusicSourceMetadata? sourceMetadata;

  /// Creates an audio chunk.
  const LiveMusicAudioChunk({this.data, this.mimeType, this.sourceMetadata});

  /// Parses an audio chunk and decodes its base64 data.
  factory LiveMusicAudioChunk.fromJson(Map<String, dynamic> json) {
    final data = json['data'] as String?;
    final metadata = json['sourceMetadata'] as Map<String, dynamic>?;
    return LiveMusicAudioChunk(
      data: data == null ? null : base64Decode(data),
      mimeType: json['mimeType'] as String?,
      sourceMetadata: metadata == null
          ? null
          : LiveMusicSourceMetadata.fromJson(metadata),
    );
  }

  /// Converts to JSON with base64-encoded audio.
  Map<String, dynamic> toJson() => {
    if (data != null) 'data': base64Encode(data!),
    'mimeType': ?mimeType,
    'sourceMetadata': ?sourceMetadata?.toJson(),
  };
}

/// Inputs the service used for an audio chunk.
class LiveMusicSourceMetadata {
  /// Prompt weights applied by the service.
  final List<LiveMusicWeightedPrompt>? weightedPrompts;

  /// Configuration applied by the service.
  final LiveMusicGenerationConfig? musicGenerationConfig;

  /// Creates source metadata.
  const LiveMusicSourceMetadata({
    this.weightedPrompts,
    this.musicGenerationConfig,
  });

  /// Parses source metadata.
  factory LiveMusicSourceMetadata.fromJson(Map<String, dynamic> json) {
    final content = json['clientContent'] as Map<String, dynamic>?;
    final config = json['musicGenerationConfig'] as Map<String, dynamic>?;
    return LiveMusicSourceMetadata(
      weightedPrompts: (content?['weightedPrompts'] as List<dynamic>?)
          ?.map(
            (prompt) => LiveMusicWeightedPrompt.fromJson(
              prompt as Map<String, dynamic>,
            ),
          )
          .toList(),
      musicGenerationConfig: config == null
          ? null
          : LiveMusicGenerationConfig.fromJson(config),
    );
  }

  /// Converts to JSON.
  Map<String, dynamic> toJson() => {
    if (weightedPrompts != null)
      'clientContent': {
        'weightedPrompts': weightedPrompts!
            .map((prompt) => prompt.toJson())
            .toList(),
      },
    'musicGenerationConfig': ?musicGenerationConfig?.toJson(),
  };
}

/// Text filtered from the prompts, with an explanation from the service.
class LiveMusicFilteredPrompt {
  /// The filtered prompt.
  final String? text;

  /// The reason supplied by the service.
  final String? filteredReason;

  /// Creates information about a filtered prompt.
  const LiveMusicFilteredPrompt({this.text, this.filteredReason});

  /// Parses information about a filtered prompt.
  factory LiveMusicFilteredPrompt.fromJson(Map<String, dynamic> json) =>
      LiveMusicFilteredPrompt(
        text: json['text'] as String?,
        filteredReason: json['filteredReason'] as String?,
      );

  /// Converts to JSON.
  Map<String, dynamic> toJson() => {
    'text': ?text,
    'filteredReason': ?filteredReason,
  };
}
