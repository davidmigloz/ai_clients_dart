/// Settings for the model that authors SVG output.
@immutable
class SvgOptions {
  /// Creates settings for SVG authoring.
  const SvgOptions({this.model, this.reasoning});

  /// Model that authors the SVG from the reference image.
  ///
  /// Required when passing these options to Images generation. Project access
  /// controls whether explicit SVG author selection is available.
  final String? model;

  /// The author's reasoning settings, independent of image complexity.
  final SvgReasoning? reasoning;

  /// Parses SVG authoring settings.
  factory SvgOptions.fromJson(Map<String, dynamic> json) => SvgOptions(
    model: optionalJsonString(json, 'model', 'SvgOptions', nullable: false),
    reasoning: json['reasoning'] == null
        ? null
        : SvgReasoning.fromJson(
            requireJsonObject(json['reasoning'], 'SvgOptions.reasoning'),
          ),
  )..validate();

  /// Checks that any specified author model and effort can be sent.
  @internal
  void validate() {
    if (model != null && model!.isEmpty) {
      throw const FormatException(
        'SvgOptions.model: expected a nonempty model',
      );
    }
    reasoning?._validate();
  }

  /// Converts to JSON.
  Map<String, dynamic> toJson() {
    validate();
    return {
      if (model != null) 'model': model,
      if (reasoning != null) 'reasoning': reasoning!.toJson(),
    };
  }

  /// Copies the settings. Passing null clears the matching option.
  SvgOptions copyWith({
    Object? model = unsetCopyWithValue,
    Object? reasoning = unsetCopyWithValue,
  }) => SvgOptions(
    model: copyImageValue<String>(model, this.model, 'SvgOptions.model'),
    reasoning: copyImageValue<SvgReasoning>(
      reasoning,
      this.reasoning,
      'SvgOptions.reasoning',
    ),
  );

  @override
  bool operator ==(Object other) =>
      other is SvgOptions &&
      runtimeType == other.runtimeType &&
      model == other.model &&
      reasoning == other.reasoning;

  @override
  int get hashCode => Object.hash(model, reasoning);
}

/// Reasoning settings for the SVG author model.
@immutable
class SvgReasoning {
  /// Creates the reasoning settings. Omit [effort] for the author's default.
  const SvgReasoning({this.effort});

  /// Desired reasoning effort for the author model.
  final ReasoningEffort? effort;

  /// Parses SVG author reasoning settings.
  factory SvgReasoning.fromJson(Map<String, dynamic> json) => SvgReasoning(
    effort: json['effort'] == null
        ? null
        : ReasoningEffort.fromJson(
            requireJsonString(json['effort'], 'SvgReasoning.effort'),
          ),
  ).._validate();

  void _validate() {
    if (effort == ReasoningEffort.unknown) {
      throw const FormatException(
        'SvgReasoning.effort: unknown reasoning effort',
      );
    }
  }

  /// Converts to JSON.
  Map<String, dynamic> toJson() {
    _validate();
    return {if (effort != null) 'effort': effort!.toJson()};
  }

  @override
  bool operator ==(Object other) =>
      other is SvgReasoning &&
      runtimeType == other.runtimeType &&
      effort == other.effort;

  @override
  int get hashCode => effort.hashCode;
}

/// SVG author token usage, separate from image generation usage.
@immutable
class SvgUsage {
  /// Creates SVG author usage.
  const SvgUsage({
    required this.model,
    required this.inputTokens,
    required this.outputTokens,
    required this.totalTokens,
    required this.reasoningTokens,
  });

  /// SVG author model used.
  final String model;

  /// Tokens sent to the author.
  final int inputTokens;

  /// Tokens generated by the author.
  final int outputTokens;

  /// Total author tokens.
  final int totalTokens;

  /// Reasoning tokens generated by the author.
  final int reasoningTokens;

  /// Parses SVG author usage.
  factory SvgUsage.fromJson(Map<String, dynamic> json) => SvgUsage(
    model: requireJsonString(json['model'], 'SvgUsage.model'),
    inputTokens: requireJsonInt(json['input_tokens'], 'SvgUsage.input_tokens'),
    outputTokens: requireJsonInt(
      json['output_tokens'],
      'SvgUsage.output_tokens',
    ),
    totalTokens: requireJsonInt(json['total_tokens'], 'SvgUsage.total_tokens'),
    reasoningTokens: requireJsonInt(
      json['reasoning_tokens'],
      'SvgUsage.reasoning_tokens',
    ),
  );

  /// Converts to JSON.
  Map<String, dynamic> toJson() => {
    'model': model,
    'input_tokens': inputTokens,
    'output_tokens': outputTokens,
    'total_tokens': totalTokens,
    'reasoning_tokens': reasoningTokens,
  };

  @override
  bool operator ==(Object other) =>
      other is SvgUsage &&
      runtimeType == other.runtimeType &&
      model == other.model &&
      inputTokens == other.inputTokens &&
      outputTokens == other.outputTokens &&
      totalTokens == other.totalTokens &&
      reasoningTokens == other.reasoningTokens;

  @override
  int get hashCode => Object.hash(
    model,
    inputTokens,
    outputTokens,
    totalTokens,
    reasoningTokens,
  );
}
